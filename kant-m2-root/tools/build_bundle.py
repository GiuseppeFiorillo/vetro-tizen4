#!/usr/bin/env python3
"""Build a single-file installer for the Vetro root boot hook.

The TV is easiest to drive through the reverse root shell, so the installer is
served as one self-contained shell script. It embeds boot.sh, root-daemon.js
and install.sh, unpacks them in /tmp on the TV and runs the installer.

Usage:
    python3 tools/build_bundle.py [--out DIR]
"""

import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)

FILES = {
    "boot.sh": os.path.join(PROJECT, "boot", "boot.sh"),
    "root-daemon.js": os.path.join(os.path.dirname(PROJECT), "chain", "daemon", "root-daemon.js"),
    "install.sh": os.path.join(PROJECT, "boot", "install.sh"),
}

DELIMS = {
    "boot.sh": "VETRO_BOOT_SH_EOF",
    "root-daemon.js": "VETRO_ROOT_DAEMON_JS_EOF",
    "install.sh": "VETRO_INSTALL_SH_EOF",
}

HEADER = """#!/bin/sh
# Self-contained Vetro root boot-hook installer.
# Generated by tools/build_bundle.py. Do not edit by hand.
set -u
TMP=$(mktemp -d /tmp/vetro-boot.XXXXXX) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM
"""

FOOTER = """
/bin/sh -s -- --payload "$TMP" "$@" < "$TMP/install.sh"
exit $?
"""


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the self-contained installer")
    ap.add_argument("--out", default=os.path.join(PROJECT, "out"))
    args = ap.parse_args(argv)

    blobs = {}
    for name, path in FILES.items():
        if not os.path.isfile(path):
            print("missing: %s" % path, file=sys.stderr)
            return 1
        text = read(path)
        if DELIMS[name] in text:
            print("delimiter collision in %s" % path, file=sys.stderr)
            return 1
        blobs[name] = text

    parts = [HEADER]
    for name in ("boot.sh", "root-daemon.js", "install.sh"):
        parts.append('\ncat > "$TMP/%s" <<\'%s\'\n' % (name, DELIMS[name]))
        parts.append(blobs[name])
        if not blobs[name].endswith("\n"):
            parts.append("\n")
        parts.append("%s\n" % DELIMS[name])
    parts.append(FOOTER)
    bundle = "".join(parts)

    os.makedirs(args.out, exist_ok=True)
    target = os.path.join(args.out, "vetro-boot-install.sh")
    with open(target, "w", encoding="utf-8") as f:
        f.write(bundle)
    os.chmod(target, 0o755)

    manifest = {
        "bundle": os.path.basename(target),
        "sha256": hashlib.sha256(bundle.encode("utf-8")).hexdigest(),
        "bytes": len(bundle),
        "embedded": {
            name: {
                "sha256": hashlib.sha256(blobs[name].encode("utf-8")).hexdigest(),
                "bytes": len(blobs[name]),
            }
            for name in blobs
        },
    }
    manifest_path = os.path.join(args.out, "vetro-boot-install.manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")

    print("wrote %s (%d bytes)" % (target, len(bundle)))
    print("sha256 %s" % manifest["sha256"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
